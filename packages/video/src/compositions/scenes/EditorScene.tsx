// The heart of the tour: mounts the REAL Flow editor (the same System/session/
// LayoutController wiring the docs-site embed uses) with an authored,
// explicitly-positioned graph loaded, themed with the flow package's built-in
// Kiberon theme, and driven from the video clock:
//
// - The editor is built asynchronously under a delayRender handle (the image
//   node pack initializes ImageMagick wasm before it can register specs).
// - Scene `actions` fire once as the playhead crosses their scene-fraction:
//   they go through the editor's real stores (selection, tabs, node ports, the
//   graph runner), so the video reads as someone actually using the tool. A
//   render worker cold-starting a chunk mid-scene replays every crossed action
//   in order; runner timing itself is wall/frame-clock, so render with
//   --concurrency=1 when exact run timing matters.
// - `imageNodes` scenes turn the `image.showPreview` system setting on BEFORE
//   anything runs, so every image node captures and shows its intermediate
//   result once the pipeline evaluates.
// - `imagePayoff` overlays the before → after card (pre-generated by
//   `pnpm image-demo` with the same ImageMagick ops the graph performs).
